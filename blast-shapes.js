// 把二维 0/1 数组压成从 (0,0) 起的 {dx, dy} 列表。
function normalize(rows) {
  let minR = Infinity, minC = Infinity, maxR = -1, maxC = -1;
  for (let r = 0; r < rows.length; r += 1) {
    for (let c = 0; c < rows[r].length; c += 1) {
      if (!rows[r][c]) continue;
      if (r < minR) minR = r;
      if (r > maxR) maxR = r;
      if (c < minC) minC = c;
      if (c > maxC) maxC = c;
    }
  }
  const cells = [];
  for (let r = minR; r <= maxR; r += 1) {
    for (let c = minC; c <= maxC; c += 1) if (rows[r][c]) cells.push(Object.freeze({ dx: c - minC, dy: r - minR }));
  }
  return Object.freeze(cells);
}

// 源表里有几组几何重复（如「長J右上」与「長L右上」），按归一化后的几何去重。
const seen = new Set();
export const BLAST_SHAPES = Object.freeze(RAW
  .map(([rows, name]) => ({ name, cells: normalize(rows) }))
  .filter((shape) => {
    const key = shape.cells.map((cell) => `${cell.dx},${cell.dy}`).join(';');
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  })
  .map((shape) => Object.freeze(shape)));
