// Builds pour-levels.js: the twelve levels of 倒水排序, each solved by pour-core's A* and
// rated by its casual-player failure rate. Run `npm run gen:pour` after changing LEVELS.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { generateLevel, LEVELS } from '../pour-core.js';

const SEED = 1;
const out = fileURLToPath(new URL('../pour-levels.js', import.meta.url));

const lines = [];
for (let stage = 1; stage <= LEVELS.length; stage += 1) {
  const t0 = Date.now();
  const def = generateLevel(stage, SEED);
  console.log(`stage ${String(stage).padStart(2)}: ${def.tubes.length - LEVELS[stage - 1].empty} colours, ${LEVELS[stage - 1].empty} spare, par ${def.par}${def.exact ? '' : '~'}, casual fail ${def.fail.toFixed(2)}  (${Date.now() - t0} ms)`);
  lines.push(`  { stage: ${def.stage}, seed: ${def.seed}, par: ${def.par}, exact: ${def.exact}, fail: ${def.fail}, tubes: ${JSON.stringify(def.tubes)} }`);
}
// LEVELS_KEY is the curve these levels were made from; the tests compare it to today's LEVELS to catch a stale file.
writeFileSync(out, `// Generated by scripts/gen-pour-levels.js from pour-core.js — do not edit by hand.\nexport const LEVELS_KEY = ${JSON.stringify(JSON.stringify(LEVELS))};\nexport const LEVEL_DEFS = [\n${lines.join(',\n')}\n];\n`);
console.log(`wrote ${out}`);
